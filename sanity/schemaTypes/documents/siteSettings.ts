import { defineField, defineType } from 'sanity'

export const siteSettings = defineType({
  name: 'siteSettings',
  title: 'Site settings',
  type: 'document',
  groups: [
    { name: 'identity', title: 'Identity', default: true },
    { name: 'links', title: 'Links & files' },
    { name: 'availability', title: 'Availability' },
    { name: 'seo', title: 'SEO' },
  ],
  fields: [
    defineField({ name: 'name', title: 'Name', type: 'string', group: 'identity', validation: (Rule) => Rule.required() }),
    defineField({
      name: 'monogram',
      title: 'Monogram',
      type: 'string',
      group: 'identity',
      description: 'Two initials shown in the header tile.',
      validation: (Rule) => Rule.required().length(2).error('Use exactly two characters.'),
    }),
    defineField({ name: 'role', title: 'Role', type: 'string', group: 'identity', validation: (Rule) => Rule.required() }),
    defineField({ name: 'location', title: 'Location', type: 'string', group: 'identity' }),
    defineField({
      name: 'footerBio',
      title: 'Footer bio',
      type: 'string',
      group: 'identity',
      description: 'One line under your name in the footer.',
    }),
    defineField({
      name: 'metaDescription',
      title: 'Meta description',
      type: 'text',
      rows: 3,
      group: 'seo',
      validation: (Rule) => Rule.required().max(160),
    }),
    defineField({
      name: 'ogImage',
      title: 'Social share image',
      type: 'imageWithAlt',
      group: 'seo',
      description: '1200×630 recommended.',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'email',
      title: 'Email',
      type: 'string',
      group: 'links',
      validation: (Rule) => Rule.required().email(),
    }),
    defineField({ name: 'linkedinUrl', title: 'LinkedIn URL', type: 'url', group: 'links' }),
    defineField({ name: 'githubUrl', title: 'GitHub URL', type: 'url', group: 'links' }),
    defineField({
      name: 'resumeFile',
      title: 'Resume (PDF)',
      type: 'file',
      group: 'links',
      options: { accept: 'application/pdf' },
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'bookingUrl',
      title: 'Booking URL',
      type: 'url',
      group: 'links',
      description: 'Optional calendar link. Shows a "Prefer a call?" card on the contact page.',
    }),
    defineField({
      name: 'availability',
      title: 'Availability',
      type: 'object',
      group: 'availability',
      fields: [
        defineField({
          name: 'show',
          title: 'Show availability badge',
          type: 'boolean',
          initialValue: false,
          description: 'Off by default. The badge is public.',
        }),
        defineField({ name: 'label', title: 'Badge label', type: 'string', description: 'e.g. Open to Senior PM roles' }),
        defineField({ name: 'targetRoles', title: 'Target roles', type: 'string' }),
        defineField({ name: 'details', title: 'Details', type: 'string', description: 'One line on the contact page.' }),
        defineField({ name: 'workStyle', title: 'Work style', type: 'string', description: 'e.g. Hybrid or remote' }),
      ],
    }),
  ],
  preview: {
    prepare: () => ({ title: 'Site settings' }),
  },
})
